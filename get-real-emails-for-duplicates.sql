-- Get REAL emails from customers table for all associate IDs with duplicates

SELECT 
  c.associate_id,
  c.company_email,
  c.first_name,
  c.last_name,
  CASE c.associate_id
    WHEN 95059 THEN 19
    WHEN 203499 THEN 14
    WHEN 200388 THEN 12
    WHEN 131252 THEN 10
    WHEN 174701 THEN 10
    WHEN 197159 THEN 9
    WHEN 409 THEN 8
    WHEN 213793 THEN 8
    WHEN 145691 THEN 4
    WHEN 155251 THEN 4
    WHEN 206353 THEN 4
    WHEN 209153 THEN 3
    WHEN 159521 THEN 2
    WHEN 167595 THEN 2
    WHEN 187440 THEN 2
    WHEN 196676 THEN 2
    WHEN 198033 THEN 2
    WHEN 205226 THEN 2
  END as duplicate_count,
  CASE c.associate_id
    WHEN 95059 THEN 152
    WHEN 203499 THEN 112
    WHEN 200388 THEN 96
    WHEN 131252 THEN 80
    WHEN 174701 THEN 80
    WHEN 197159 THEN 72
    WHEN 409 THEN 64
    WHEN 213793 THEN 64
    WHEN 145691 THEN 32
    WHEN 155251 THEN 32
    WHEN 206353 THEN 32
    WHEN 209153 THEN 24
    WHEN 159521 THEN 16
    WHEN 167595 THEN 16
    WHEN 187440 THEN 16
    WHEN 196676 THEN 16
    WHEN 198033 THEN 16
    WHEN 205226 THEN 16
  END as credits_to_add
FROM customers c
WHERE c.associate_id IN (
  95059, 203499, 200388, 131252, 174701, 197159, 409, 213793,
  145691, 155251, 206353, 209153, 159521, 167595, 187440,
  196676, 198033, 205226
)
ORDER BY credits_to_add DESC;

