/**
 * Returns whether the request path is allowed for the given section.
 * Shell: allow non-API paths and /health (SPA + static). Others: prefix match.
 */
export function isPathAllowedForSection(path: string, section: SectionName): boolean {
  const normalizedPath = path.split('?')[0];
  if (section === 'shell') {
    // Shell is a full proxy — allow all paths, upstream routing handles filtering
    return true;
  }
  const prefixes = SECTION_PATH_PREFIXES[section];
  return prefixes.some((prefix) => normalizedPath === prefix || normalizedPath.startsWith(prefix + '/'));
}

export function getSectionPathPrefixes(section: SectionName): readonly string[] {
  return SECTION_PATH_PREFIXES[section];
}
